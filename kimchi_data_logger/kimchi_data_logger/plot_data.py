def main():
    """Main function."""
    args = parse_args()
    
    # Determine file paths
    if args.log_dir and args.session:
        log_dir = os.path.expanduser(args.log_dir)
        odom_file = os.path.join(log_dir, f'odom_{args.session}.csv')
        cmd_vel_file = os.path.join(log_dir, f'cmd_vel_{args.session}.csv')
    else:
        odom_file = args.odom
        cmd_vel_file = args.cmd_vel
    
    # Create output directory
    output_dir = os.path.expanduser(args.output)
    Path(output_dir).mkdir(parents=True, exist_ok=True)
    
    # Read data files
    df_odom = None
    df_cmd = None
    
    if odom_file and os.path.exists(os.path.expanduser(odom_file)):
        odom_file = os.path.expanduser(odom_file)
        print(f"Reading odometry data from: {odom_file}")
        df_odom = pd.read_csv(odom_file)
        print(f"Loaded {len(df_odom)} odometry records")
    else:
        print(f"Odometry file not found: {odom_file}")
    
    if cmd_vel_file and os.path.exists(os.path.expanduser(cmd_vel_file)):
        cmd_vel_file = os.path.expanduser(cmd_vel_file)
        print(f"Reading cmd_vel data from: {cmd_vel_file}")
        df_cmd = pd.read_csv(cmd_vel_file)
        print(f"Loaded {len(df_cmd)} cmd_vel records")
    else:
        print(f"Cmd_vel file not found: {cmd_vel_file}")
    
    # Generate plots
    if df_odom is not None:
        plot_odometry(df_odom, output_dir)
    
    # if df_cmd is not None:
    #     plot_cmd_vel(df_cmd, output_dir)
    
    if df_odom is not None and df_cmd is not None:
        plot_comparison(df_odom, df_cmd, output_dir)
    
    print("\nPlotting complete!")


if __name__ == '__main__':
    main()
