#!/usr/bin/env python3
"""
Plot data from CSV log files generated by the data logger node.

This script reads odometry and cmd_vel data from CSV files and creates
various plots for analysis.
"""

import argparse
import pandas as pd
import matplotlib.pyplot as plt
import numpy as np
from pathlib import Path
import os


def parse_args():
    """Parse command line arguments."""
    parser = argparse.ArgumentParser(
        description='Plot data from kimchi data logger CSV files'
    )
    parser.add_argument(
        '--odom',
        type=str,
        help='Path to odometry CSV file'
    )
    parser.add_argument(
        '--cmd_vel',
        type=str,
        help='Path to cmd_vel CSV file'
    )
    parser.add_argument(
        '--log_dir',
        type=str,
        help='Directory containing log files'
    )
    parser.add_argument(
        '--session',
        type=str,
        help='Session name to plot'
    )
    parser.add_argument(
        '--output',
        type=str,
        default='plots',
        help='Output directory for plots (default: plots)'
    )
    return parser.parse_args()


def quaternion_to_euler(x, y, z, w):
    """Convert quaternion to Euler angles (roll, pitch, yaw)."""
    # Roll (x-axis rotation)
    sinr_cosp = 2 * (w * x + y * z)
    cosr_cosp = 1 - 2 * (x * x + y * y)
    roll = np.arctan2(sinr_cosp, cosr_cosp)
    
    # Pitch (y-axis rotation)
    sinp = 2 * (w * y - z * x)
    pitch = np.where(np.abs(sinp) >= 1, np.copysign(np.pi / 2, sinp), np.arcsin(sinp))
    
    # Yaw (z-axis rotation)
    siny_cosp = 2 * (w * z + x * y)
    cosy_cosp = 1 - 2 * (y * y + z * z)
    yaw = np.arctan2(siny_cosp, cosy_cosp)
    
    return roll, pitch, yaw


def plot_odometry(df_odom, output_dir):
    """Plot odometry data."""
    if df_odom is None or df_odom.empty:
        print("No odometry data to plot")
        return
    
    # Create time column in seconds
    df_odom['time'] = df_odom['timestamp_sec'] + df_odom['timestamp_nsec'] * 1e-9
    df_odom['time'] = df_odom['time'] - df_odom['time'].iloc[0]
    
    # Convert quaternion to euler angles
    roll, pitch, yaw = quaternion_to_euler(
        df_odom['orient_x'].values,
        df_odom['orient_y'].values,
        df_odom['orient_z'].values,
        df_odom['orient_w'].values
    )
    df_odom['yaw'] = yaw
    
    # Create plots
    fig, axes = plt.subplots(2, 2, figsize=(15, 10))
    fig.suptitle('Odometry Data', fontsize=16)
    
    # Plot 1: 2D trajectory
    axes[0, 0].plot(df_odom['pos_x'], df_odom['pos_y'], 'b-', linewidth=2)
    axes[0, 0].plot(df_odom['pos_x'].iloc[0], df_odom['pos_y'].iloc[0], 'go', 
                     markersize=10, label='Principio')
    axes[0, 0].plot(df_odom['pos_x'].iloc[-1], df_odom['pos_y'].iloc[-1], 'ro', 
                     markersize=10, label='Final')
    axes[0, 0].set_xlabel('X (m)')
    axes[0, 0].set_ylabel('Y (m)')
    axes[0, 0].set_title('Trayectoria del Robot')
    axes[0, 0].grid(True)
    axes[0, 0].legend()
    axes[0, 0].axis('equal')
    
    # Plot 2: Position over time
    axes[0, 1].plot(df_odom['time'], df_odom['pos_x'], 'r-', label='X')
    # axes[0, 1].plot(df_odom['time'], df_odom['pos_y'], 'g-', label='Y')
    axes[0, 1].set_xlabel('Tiempo (s)')
    axes[0, 1].set_ylabel('Posición (m)')
    axes[0, 1].set_title('Posición vs Tiempo')
    axes[0, 1].grid(True)
    axes[0, 1].set_ylim(17.5, 23)
    axes[0, 1].legend()
    # Plot 3: Yaw angle over time
    axes[1, 0].plot(df_odom['time'], np.degrees(df_odom['yaw']), 'b-', linewidth=2)
    axes[1, 0].set_xlabel('Tiempo (s)')
    axes[1, 0].set_ylabel('Ángulo de Yaw (grados)')
    axes[1, 0].set_title('Ángulo de Yaw vs Tiempo')
    axes[1, 0].grid(True)
    
    # Plot 4: Velocities over time
    axes[1, 1].plot(df_odom['time'], df_odom['linear_vel_x'], 'r-', label='Velocidad Lineal X')
    axes[1, 1].plot(df_odom['time'], df_odom['angular_vel_z'], 'b-', label='Velocidad Angular Z')
    axes[1, 1].set_xlabel('Tiempo (s)')
    axes[1, 1].set_ylabel('Velocidad (m/s o rad/s)')
    axes[1, 1].set_title('Velocidades vs Tiempo (desde Odometría)')
    axes[1, 1].grid(True)
    axes[1, 1].legend()
    
    plt.tight_layout()
    output_path = os.path.join(output_dir, 'odometry_plots.png')
    plt.savefig(output_path, dpi=300, bbox_inches='tight')
    print(f"Saved odometry plots to: {output_path}")
    plt.show()


